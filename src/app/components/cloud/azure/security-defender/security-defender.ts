    solution: `interface SecurityControl {
  name: string;
  maxPoints: number;
  healthyResources: number;
  unhealthyResources: number;
}

export function calculateSecureScore(controls: SecurityControl[]) {
  const applicable = controls.filter(c => c.healthyResources + c.unhealthyResources > 0);

  const breakdown = applicable.map(c => {
    const total = c.healthyResources + c.unhealthyResources;
    const ratio = c.healthyResources / total;
    const earned = Math.round(c.maxPoints * ratio * 100) / 100;
    const percentHealthy = Math.round(ratio * 100);
    return { name: c.name, earned, max: c.maxPoints, percentHealthy };
  });

  breakdown.sort((a, b) => a.earned - b.earned);

  const totalEarned = breakdown.reduce((s, c) => s + c.earned, 0);
  const totalMax = breakdown.reduce((s, c) => s + c.max, 0);
  const secureScore = totalMax > 0 ? Math.round((totalEarned / totalMax) * 100 * 10) / 10 : 0;

  const topPriority = [...breakdown]
    .filter(c => c.max > 0)
    .sort((a, b) => (a.earned / a.max) - (b.earned / b.max))[0]?.name ?? '';

  return { secureScore, controlBreakdown: breakdown, topPriority };
}`
