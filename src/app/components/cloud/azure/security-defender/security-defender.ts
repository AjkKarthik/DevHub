    description: 'Calculate a Defender for Cloud Secure Score from security control data.\n\nGiven:\n```typescript\ninterface SecurityControl {\n  name: string;\n  maxPoints: number;\n  healthyResources: number;\n  unhealthyResources: number;\n}\n```\n\nWrite `calculateSecureScore(controls: SecurityControl[])`:\n- Each control earns points proportional to its healthy resource ratio: `maxPoints × (healthy / (healthy + unhealthy))`\n- If a control has 0 resources total, exclude it from the calculation (not applicable)\n- `secureScore`: number 0–100 (percentage of total earned vs total max)\n- `controlBreakdown`: array of `{ name, earned, max, percentHealthy }` sorted by earned points ascending (lowest first — what to fix first)\n- `topPriority`: name of the control with the most potential improvement (lowest earned/max ratio)',
