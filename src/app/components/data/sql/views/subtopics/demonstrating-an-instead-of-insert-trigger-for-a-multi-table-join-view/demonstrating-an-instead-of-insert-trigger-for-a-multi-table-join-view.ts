    solution: `SCOPE_IDENTITY() returns only the LAST identity value generated by
the most recent INSERT statement in the current scope — it has no
way to return multiple values for a multi-row insert. When the ORM's
batched INSERT puts several rows into "inserted" at once, the trigger's
"INSERT INTO customers ... SELECT name FROM inserted" creates several
new customer rows, but @NewCustomerId only captures the LAST one's
ID. The subsequent "INSERT INTO addresses ... SELECT @NewCustomerId,
..." then attaches every address row to that single last customer_id,
silently misassigning every other row's address.

Manual testing missed this because each manual test almost certainly
inserted ONE row at a time, where SCOPE_IDENTITY() genuinely does
return the correct (and only) new ID. The bug only appears once
"inserted" contains more than one row — exactly the third code tab's
scenario, which is why the production-correct version uses OUTPUT to
capture a customer_id for EACH inserted row individually, then joins
back to route each address to its own correct customer, instead of
relying on a single scalar SCOPE_IDENTITY() value.`,
