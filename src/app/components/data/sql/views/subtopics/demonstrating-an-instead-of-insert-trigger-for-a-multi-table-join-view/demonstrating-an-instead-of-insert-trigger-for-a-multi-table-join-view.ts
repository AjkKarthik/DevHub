      label: 'Handling a multi-row INSERT correctly',
      language: 'sql',
      code: `-- This single-row example works, but a naive real-world version of
-- this trigger would break on a MULTI-ROW insert, since SCOPE_IDENTITY()
-- only returns the last identity value generated, not one per row.
-- A production-correct version uses OUTPUT to pair each new customer_id
-- back to its originating row:
ALTER TRIGGER trg_customer_with_address_insert
ON v_customer_with_address
INSTEAD OF INSERT
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @NewCustomers TABLE (NewCustomerId INT, Name VARCHAR(100));

    INSERT INTO customers (name)
    OUTPUT inserted.customer_id, inserted.name INTO @NewCustomers
    SELECT name FROM inserted;

    INSERT INTO addresses (customer_id, street, city)
    SELECT nc.NewCustomerId, i.street, i.city
    FROM inserted i
    JOIN @NewCustomers nc ON nc.Name = i.name;
END;
GO

-- Now correctly handles multiple rows in a single INSERT statement,
-- each getting its own newly generated customer_id paired to its
-- own street/city -- SCOPE_IDENTITY() alone would have silently
-- paired every address row to just the LAST customer inserted.`,
